/** Seconds on a clock that only runs forward, for the animation. */
function monotonic(): number {
  return performance.now() / 1000;
}

/** a % b for whole numbers that is never negative for a positive b. */
function mod(a: number, b: number): number {
  return ((a % b) + b) % b;
}

function clamp(value: number, low: number, high: number): number {
  return Math.min(high, Math.max(low, value));
}

function bitmap(image: Image, x: number, y: number, sprite: Bitmap, scale = 1.0): void {
  let [color] = sprite;
  if (scale !== 1.0) {
    color = [Math.trunc(color[0] * scale), Math.trunc(color[1] * scale), Math.trunc(color[2] * scale)];
  }
  sprite[1].forEach((row, dy) => {
    for (let dx = 0; dx < row.length; dx++) {
      if (row[dx] === "X") {
        image.point(x + dx, y + dy, color);
      }
    }
  });
}

