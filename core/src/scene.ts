function flickerFlame(mood: string): string | null {
  if (["sad", "sick", "tired"].includes(mood)) {
    return "blue";
  }
  if (mood === "happy") {
    return "gold";
  }
  return null;
}

/** Widen in the middle (repeat the center column); the height stays. */
function widen(img: Image, extra: number): Image {
  const cx = Math.floor(img.width / 2);
  const out = new Image(img.width + extra, img.height);
  out.blit(img.crop(0, 0, cx, img.height), 0, 0);
  for (let i = 0; i < extra; i++) {
    out.blit(img.crop(cx, 0, cx + 1, img.height), cx + i, 0);
  }
  out.blit(img.crop(cx, 0, img.width, img.height), cx + extra, 0);
  return out;
}

/** Turned around the vertical axis (spin): f = 1 from the front, 0 from the side, -1 mirrored. */
function turned(img: Image, f: number): Image {
  const width = Math.max(2, Math.round(img.width * Math.abs(f)));
  let side = img.resized(width, img.height);
  if (f < 0) {
    side = side.mirrored();
  }
  const out = new Image(img.width, img.height);
  out.blit(side, Math.floor((img.width - width) / 2), 0);
  return out;
}

/** Rotated around the center of the figure (flip), with SPIN_PAD pixels of margin for the corners. */
function spun(img: Image, angle: number): Image {
  const box = img.bbox()!;
  const out = new Image(img.width + 2 * SPIN_PAD, img.height + 2 * SPIN_PAD);
  out.blit(img, SPIN_PAD, SPIN_PAD);
  return out.rotated(angle, [(box[0] + box[2]) / 2 + SPIN_PAD, (box[1] + box[3]) / 2 + SPIN_PAD]);
}

/**
 * Hat on the head: centered above the first row that is at least 8 pixels wide.
 * `pokeThrough`: what grows above that row (the lure, Flicker's flame) stays in front of the hat.
 */
function withHat(img: Image, hat: Image, pokeThrough = false): Image {
  const [top, rows] = wideRow(img);
  const cx = rows[top].length ? (rows[top][0] + rows[top].at(-1)! + 1) / 2 : img.width / 2;
  const out = img.copy();
  out.alphaComposite(hat, Math.max(0, Math.round(cx - hat.width / 2)), Math.max(0, top + HAT_SINK - hat.height));
  if (pokeThrough && top) {
    out.alphaComposite(img.crop(0, 0, img.width, top));
  }
  return out;
}

