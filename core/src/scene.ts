/** The colors a form swaps for the weather at time t, and a key for the cache; null if none. */
export function skyColors(species: string, look: SkyLook, t: number): [string, (readonly [Color, Color])[]] | null {
  if (species === "rumblefluff" && look === "storm") {
    const flash = t % 5 < 0.12 || (t % 5 > 0.25 && t % 5 < 0.35); // a double flash every few seconds
    return flash ? ["flash", HORNS.map((from, i) => [from, HORNS_FLASH[i]] as const)] : null;
  }
  if (species === "prismist" && (look === "rain" || look === "storm")) {
    return ["faded", RAINBOW.map((from) => [from, lerp(from, FADED, 0.6)] as const)];
  }
  if (species === "prismist" && look === "after_rain") {
    const step = Math.floor(t / 0.2) % RAINBOW.length;
    return [`run${step}`, RAINBOW.map((from, i) => [from, RAINBOW[(i + step) % RAINBOW.length]] as const)];
  }
  return null;
}
/**
 * Lunarock's moonstone as the moon is tonight: lit from the right while it waxes, from the left while
 * it wanes (as PetScene.drawMoon). Before GLOWS turns it into its night color.
 */
function moonstone(img: Image, phase: number, glow: boolean): Image {
  const lit = glow ? MOONSTONE_GLOW : MOONSTONE;
  const out = img.copy();
  const data = out.data;
  const at = (x: number, y: number) => (y * img.width + x) * 4;
  const isLit = (i: number) => data[i + 3] > 0 && data[i] === lit[0] && data[i + 1] === lit[1] && data[i + 2] === lit[2];
  let left = img.width;
  let right = -1;
  for (let y = 0; y < img.height; y++) {
    for (let x = 0; x < img.width; x++) {
      if (isLit(at(x, y))) {
        left = Math.min(left, x);
        right = Math.max(right, x);
      }
    }
  }
  const k = Math.cos(2 * Math.PI * phase); // 1 at new moon, -1 at full moon
  for (let y = 0; y < img.height; y++) {
    for (let x = left; x <= right; x++) {
      const u = (x - left + 0.5) / (right - left + 1) * 2 - 1; // -1 at the left edge, 1 at the right one
      if (isLit(at(x, y)) && (phase < 0.5 ? u : -u) <= k) {
        data.set(MOONSTONE_DARK, at(x, y));
      }
    }
  }
  return out;
}

