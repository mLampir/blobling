/** How high a thrown item is `e` seconds after the throw: it drops in from above and bounces once. */
function dropLift(e: number): number {
  if (e < THROW_FALL) {
    return (GROUND + 2) * (1 - (e / THROW_FALL) ** 2); // starts just above the top edge
  }
  return Math.sin(Math.min(1.0, (e - THROW_FALL) / THROW_BOUNCE) * Math.PI) * 3;
}

/** White silhouette (flash of light when evolving and hatching). */
function white(img: Image): Image {
  const out = Image.filled(img.width, img.height, [255, 255, 240]);
  for (let i = 3; i < out.data.length; i += 4) {
    out.data[i] = img.data[i];
  }
  return out;
}

